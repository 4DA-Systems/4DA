use super::*;

fn read(name: &str, format: LockFormat, content: &str) -> LockfileRead {
    read_in(&MemFs::new(), name, format, content)
}

fn read_in(fs: &MemFs, name: &str, format: LockFormat, content: &str) -> LockfileRead {
    match read_text(fs, name, format, content) {
        LockfileOutcome::Read(read) => read,
        other => panic!("{name} did not read: {other:?}"),
    }
}

fn ids(read: &LockfileRead) -> Vec<String> {
    let mut v: Vec<String> = read
        .packages
        .iter()
        .map(|p| format!("{}@{}", p.name, p.version))
        .collect();
    v.sort();
    v
}

fn find<'a>(read: &'a LockfileRead, name: &str, version: &str) -> &'a LockedPackage {
    read.packages
        .iter()
        .find(|p| p.name == name && p.version == version)
        .unwrap_or_else(|| panic!("{name}@{version} in {:?}", ids(read)))
}

#[test]
fn package_lock_v3_keeps_nested_copies_aliases_and_drops_links() {
    let lock = r#"{"name":"app","lockfileVersion":3,"packages":{
        "":{"name":"app","workspaces":["packages/*"]},
        "node_modules/semver":{"version":"7.6.0"},
        "node_modules/@babel/core":{"version":"7.24.0","dev":true},
        "node_modules/@babel/core/node_modules/semver":{"version":"6.3.1","dev":true},
        "node_modules/string-width-cjs":{"name":"string-width","version":"4.2.3"},
        "node_modules/my-lib":{"resolved":"packages/my-lib","link":true},
        "packages/my-lib":{"name":"my-lib","version":"1.0.0"},
        "packages/my-lib/node_modules/lodash":{"version":"4.17.20"},
        "node_modules/gitdep":{"version":"git+ssh://git@github.com/x/y.git#abc"}
    }}"#;
    let read = read("package-lock.json", LockFormat::NpmLock, lock);
    assert_eq!(
        ids(&read),
        [
            "@babel/core@7.24.0",
            "lodash@4.17.20",
            "semver@6.3.1",
            "semver@7.6.0",
            "string-width@4.2.3"
        ]
    );
    assert!(find(&read, "semver", "7.6.0").primary);
    assert!(!find(&read, "semver", "6.3.1").primary);
    assert_eq!(find(&read, "semver", "6.3.1").scope, DepScope::Dev);
    assert_eq!(find(&read, "semver", "7.6.0").scope, DepScope::Runtime);
    assert_eq!(read.non_registry_entries, 3, "link + workspace dir + git");
}

