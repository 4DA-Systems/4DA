#[test]
fn requirements_pins_hashes_extras_markers_and_includes() {
    let content = "\
# Reference stack
-r base.txt
aiohttp==3.9.1 \\
    --hash=sha256:aaa \\
    --hash=sha256:bbb
pillow==10.3.0  # imaging
fastapi[all]==0.111.0
uvicorn==0.29.0 ; python_version >= '3.8'
weird===1.0.0
numpy>=1.26.0
django==4.2.*
-e .
git+https://github.com/x/y.git#egg=y
";
    // base.txt and requirements-dev.txt include each other: the cycle guard
    // reads each once.
    let fs = MemFs::new()
        .with("/p/base.txt", "click==8.1.7\n-r requirements-dev.txt\n")
        .with("/p/requirements-dev.txt", "-r ./base.txt\npytest==8.0.0\n")
        .with("/p/requirements.txt", content);
    let read = read_in(
        &fs,
        "/p/requirements.txt",
        LockFormat::Requirements,
        content,
    );
    assert_eq!(
        ids(&read),
        [
            "aiohttp@3.9.1",
            "click@8.1.7",
            "fastapi@0.111.0",
            "pillow@10.3.0",
            "pytest@8.0.0",
            "uvicorn@0.29.0",
            "weird@1.0.0"
        ]
    );
}

