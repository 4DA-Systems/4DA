#[test]
fn read_dir_reports_unsupported_and_orphan_go_sum() {
    let fs = MemFs::new()
        .with("/d/pom.xml", "<project/>")
        .with("/d/bun.lockb", "\u{0}\u{1}")
        .with("/d/go.sum", "github.com/a/a v1.0.0 h1:x=\n")
        .with("/d/package-lock.json", "{ broken");
    let outcomes = read_dir(&fs, "/d");
    let kinds: Vec<(&str, &str)> = outcomes
        .iter()
        .map(|o| match o {
            LockfileOutcome::Read(r) => ("read", r.path.as_str()),
            LockfileOutcome::Failed { path, .. } => ("failed", path.as_str()),
            LockfileOutcome::Unsupported { path, .. } => ("unsupported", path.as_str()),
        })
        .collect();
    assert_eq!(
        kinds,
        [
            ("failed", "/d/package-lock.json"),
            ("failed", "/d/go.sum"),
            ("unsupported", "/d/bun.lockb"),
            ("unsupported", "/d/pom.xml"),
        ]
    );
    assert_eq!(probe(&fs, "/d").as_deref(), Some("/d/package-lock.json"));
    assert_eq!(probe(&fs, "/elsewhere"), None);
}

