#[test]
fn an_unreadable_file_is_a_failure_that_says_why() {
    struct Denied;
    impl FileSource for Denied {
        fn read(&self, _: &str) -> Result<String, String> {
            Err("access denied".to_string())
        }
        fn is_file(&self, path: &str) -> bool {
            path.ends_with("uv.lock") || path.ends_with("requirements.txt")
        }
        fn list(&self, dir: &str) -> Option<Vec<Entry>> {
            (dir == "/d").then(|| {
                vec![Entry {
                    name: "requirements.txt".to_string(),
                    is_file: true,
                }]
            })
        }
    }
    let reasons: Vec<String> = read_dir(&Denied, "/d")
        .into_iter()
        .map(|o| match o {
            LockfileOutcome::Failed { path, reason, .. } => format!("{path}: {reason}"),
            other => format!("{other:?}"),
        })
        .collect();
    assert_eq!(
        reasons,
        [
            "/d/uv.lock: unreadable: access denied",
            "/d/requirements.txt: unreadable: access denied"
        ]
    );
}
