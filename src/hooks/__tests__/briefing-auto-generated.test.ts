import { describe, it, expect, beforeEach, vi } from 'vitest';
import type { Event } from '@tauri-apps/api/event';
import { invoke } from '@tauri-apps/api/core';
import { useAppStore } from '../../store';
import { handleBriefingAutoGenerated, type BriefingAutoGeneratedPayload } from '../analysis-event-handlers';

vi.mock('@tauri-apps/api/core', () => ({ invoke: vi.fn() }));

const initialState = useAppStore.getState();

function event(payload: BriefingAutoGeneratedPayload): Event<BriefingAutoGeneratedPayload> {
  return { event: 'briefing-auto-generated', id: 1, payload } as Event<BriefingAutoGeneratedPayload>;
}

describe('briefing-auto-generated', () => {
  beforeEach(() => {
    useAppStore.setState(initialState, true);
    vi.mocked(invoke).mockReset();
    vi.mocked(invoke).mockResolvedValue({ filtered: [], expires_in_seconds: 0 });
    useAppStore.setState({
      aiBriefing: {
        content: 'Yesterday\'s brief',
        loading: false,
        error: null,
        model: 'deterministic',
        lastGenerated: new Date('2026-11-10T08:00:00Z'),
      },
    });
  });

  // Audit 2026-11-11: the payload was dropped, so a toast announced a new
  // brief while the tab kept showing the old one.
  it('shows the brief the toast announces', () => {
    handleBriefingAutoGenerated(event({ briefing: '## Act now\n- lodash', model: 'claude-sonnet-5' }));
    const { aiBriefing, toasts } = useAppStore.getState();
    expect(aiBriefing.content).toBe('## Act now\n- lodash');
    expect(aiBriefing.model).toBe('claude-sonnet-5');
    expect(toasts).toHaveLength(1);
  });

  it('announces nothing for a reused brief, and keeps its real age', () => {
    handleBriefingAutoGenerated(event({
      briefing: 'Same brief',
      model: 'deterministic',
      cached: true,
      briefing_created_at: '2026-11-12 01:30:00',
    }));
    const { aiBriefing, toasts } = useAppStore.getState();
    expect(aiBriefing.content).toBe('Same brief');
    expect(aiBriefing.lastGenerated?.toISOString()).toBe('2026-11-12T01:30:00.000Z');
    expect(toasts).toHaveLength(0);
  });

  it('a facts brief served after a model failure says why, without an error', () => {
    handleBriefingAutoGenerated(event({
      briefing: 'Facts',
      model: 'deterministic',
      narration_error: 'Could not reach your AI provider.',
    }));
    const { aiBriefing } = useAppStore.getState();
    expect(aiBriefing.content).toBe('Facts');
    expect(aiBriefing.error).toBeNull();
    expect(aiBriefing.notice).toContain('Could not reach your AI provider.');
  });
});
