//! The file-system half: finding the lockfile and the workspace manifest.
//! The rules over lockfile text are tested in the engine crate
//! (`crates/fourda-depengine/src/lockfile/cargo_facts_tests.rs`).
use super::*;
use crate::ace::scanner::ProjectScanner;

/// The live shape: a workspace whose members (`acme-core`, `acme-cli`) carry
/// no `source`, next to registry crates. `acme-plugin` also resolves from the
/// registry at another version (a consumer pin), so it is NOT local-only.
const WORKSPACE_LOCK: &str = r#"# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "acme-cli"
version = "0.8.8"
dependencies = [
 "acme-core",
 "clap",
 "tempfile",
]

[[package]]
name = "acme-core"
version = "0.8.8"
dependencies = [
 "serde",
]

[[package]]
name = "acme-plugin"
version = "0.8.8"

[[package]]
name = "acme-plugin"
version = "0.7.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "00"

[[package]]
name = "clap"
version = "4.5.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
dependencies = [
 "clap_lex",
]

[[package]]
name = "clap_lex"
version = "0.7.0"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "serde"
version = "1.0.200"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "tempfile"
version = "3.10.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
dependencies = [
 "fastrand",
]

[[package]]
name = "fastrand"
version = "2.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
"#;

#[test]
fn workspace_inherited_path_dependency_is_dropped_from_a_member_manifest() {
    let tmp = tempfile::tempdir().expect("tempdir");
    let root = tmp.path();
    std::fs::create_dir(root.join(".git")).expect("git");
    std::fs::write(
        root.join("Cargo.toml"),
        "[workspace]\nmembers = [\"crates/*\"]\n\n[workspace.dependencies]\n\
         acme-core = { path = \"crates/acme-core\", version = \"0.8.8\" }\n\
         serde = \"1\"\n",
    )
    .expect("root manifest");
    let member = root.join("crates").join("acme-cli");
    std::fs::create_dir_all(&member).expect("member dir");
    let manifest = member.join("Cargo.toml");
    std::fs::write(
        &manifest,
        "[package]\nname = \"acme-cli\"\n\n[dependencies]\nacme-core = { workspace = true }\n\
         serde.workspace = true\n",
    )
    .expect("member manifest");

    // No lockfile yet: the workspace's `path` declaration is the evidence.
    let local = workspace_local_crate_names(&manifest);
    assert!(local.contains("acme-core"), "{local:?}");
    assert!(!local.contains("serde"));

    let scanner = ProjectScanner::new();
    let mut signal = crate::ace::scanner::ProjectSignal {
        manifest_type: crate::ace::scanner::ManifestType::CargoToml,
        manifest_path: manifest.clone(),
        project_name: None,
        languages: vec!["rust".to_string()],
        frameworks: Vec::new(),
        dependencies: Vec::new(),
        dev_dependencies: Vec::new(),
        indirect_dependencies: Vec::new(),
        target_dependencies: Vec::new(),
        detected_at: String::new(),
        project_license: None,
        project_relevance: 1.0,
    };
    let text = std::fs::read_to_string(&manifest).expect("read");
    scanner.parse_cargo_toml(&text, &mut signal);
    assert!(signal.dependencies.contains(&"acme-core".to_string()));
    drop_local_crates(&local, &mut signal);
    assert_eq!(signal.dependencies, vec!["serde".to_string()]);

    // With a lockfile, its source-less members are local too.
    std::fs::write(root.join("Cargo.lock"), WORKSPACE_LOCK).expect("lock");
    let local = workspace_local_crate_names(&manifest);
    assert!(local.contains("acme-cli") && local.contains("acme-core"));
}

#[test]
fn the_lockfile_search_stops_at_the_repository_root() {
    let tmp = tempfile::tempdir().expect("tempdir");
    std::fs::write(tmp.path().join("Cargo.lock"), WORKSPACE_LOCK).expect("outer lock");
    let repo = tmp.path().join("repo");
    std::fs::create_dir_all(repo.join(".git")).expect("repo");
    let member = repo.join("crate");
    std::fs::create_dir_all(&member).expect("member");
    assert_eq!(
        nearest_cargo_lock(&member),
        None,
        "a lockfile outside the repository belongs to another project"
    );
}
