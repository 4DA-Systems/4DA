#[test]
fn bun_lock_reads_nested_copies_with_scope() {
    let lock = r#"{
  "lockfileVersion": 1,
  "workspaces": {
    "": {
      "name": "app",
      "dependencies": { "next": "^15.0.0", },
      "devDependencies": { "typescript": "^5", },
    },
    "packages/ui": { "name": "ui", },
  },
  "packages": {
    "next": ["next@15.0.3", "", { "dependencies": { "postcss": "8.4.31", }, }, "sha512-a"],
    "next/postcss": ["postcss@8.4.31", "", {}, "sha512-b"],
    "postcss": ["postcss@8.4.49", "", {}, "sha512-c"],
    "typescript": ["typescript@5.6.3", "", {}, "sha512-d"],
    "ui": ["ui@workspace:packages/ui"],
  }
}"#;
    let read = read("bun.lock", LockFormat::Bun, lock);
    assert_eq!(
        ids(&read),
        [
            "next@15.0.3",
            "postcss@8.4.31",
            "postcss@8.4.49",
            "typescript@5.6.3"
        ]
    );
    assert_eq!(find(&read, "postcss", "8.4.31").scope, DepScope::Runtime);
    assert!(!find(&read, "postcss", "8.4.31").primary);
    assert_eq!(find(&read, "postcss", "8.4.49").scope, DepScope::Unknown);
    assert!(find(&read, "postcss", "8.4.49").primary);
    assert_eq!(find(&read, "typescript", "5.6.3").scope, DepScope::Dev);
    assert_eq!(read.non_registry_entries, 1);
}

