#[test]
fn requirements_variants_and_requirements_dir_are_found() {
    let tmp = tempfile::tempdir().unwrap();
    let dir = tmp.path();
    for name in [
        "requirements.txt",
        "requirements-dev.txt",
        "_test_minimum_requirements.txt",
        "notes.txt",
    ] {
        std::fs::write(dir.join(name), "x==1.0\n").unwrap();
    }
    std::fs::create_dir_all(dir.join("requirements")).unwrap();
    std::fs::write(dir.join("requirements").join("base.txt"), "y==2.0\n").unwrap();
    let names: Vec<String> = requirements_files(dir)
        .iter()
        .map(|p| p.file_name().unwrap().to_string_lossy().to_string())
        .collect();
    assert_eq!(
        names,
        [
            "_test_minimum_requirements.txt",
            "base.txt",
            "requirements-dev.txt",
            "requirements.txt"
        ]
    );
    assert!(
        requirements_files(&dir.join("requirements")).is_empty(),
        "the parent owns requirements/"
    );
}

const GO_MOD_117: &str = "module example.com/app

go 1.21

require (
	github.com/gin-gonic/gin v1.9.1
	golang.org/x/net v0.0.0-20220722155237-a158d28d115b // indirect
	github.com/old/thing v1.0.0
	github.com/local/thing v0.1.0
)

require github.com/pkg/errors v0.9.1+incompatible // indirect

replace github.com/old/thing => github.com/new/thing v1.2.0

replace github.com/local/thing => ../thing
";

#[test]
fn go_mod_117_is_the_build_list_with_replaces_applied() {
    let tmp = tempfile::tempdir().unwrap();
    let path = tmp.path().join("go.mod");
    // A go.sum full of historical versions must NOT be read for go >= 1.17.
    std::fs::write(
        tmp.path().join("go.sum"),
        "github.com/gin-gonic/gin v1.6.0 h1:x=\ngithub.com/hist/only v0.1.0/go.mod h1:y=\n",
    )
    .unwrap();
    let read = read(&path.display().to_string(), LockFormat::GoMod, GO_MOD_117);
    assert_eq!(
        ids(&read),
        [
            "github.com/gin-gonic/gin@1.9.1",
            "github.com/new/thing@1.2.0",
            "github.com/pkg/errors@0.9.1+incompatible",
            "golang.org/x/net@0.0.0-20220722155237-a158d28d115b"
        ]
    );
    assert_eq!(read.non_registry_entries, 1, "the local replace");
}

